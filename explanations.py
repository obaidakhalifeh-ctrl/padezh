def _prep_key(prep, code):
    p = PREP_NORM.get(prep, prep)
    return f"{p}+{code}" if f"{p}+{code}" in PREP_INFO else p


def deep_blocks(r):
    """قائمة بلوكات الشرح: (أيقونة، عنوان، نص HTML آمن)"""
    code = r.get("case_code")
    kind = r.get("reason_kind", "none")
    key = r.get("reason_key", "")
    word = esc(r.get("word", ""))
    head = esc(r.get("head", ""))
    blocks = []
    cname = f"{RU[code]} ({SHORT[code]})" if code in RU else ""

    if kind == "prep":
        pk = _prep_key(key, code)
        p = PREP_NORM.get(key, key)
        info = PREP_INFO.get(pk) or PREP_INFO.get(p)
        mean = f" ({esc(info[0])})" if info else ""
        multi = "+" in pk
        blocks.append(("📌", "القاعدة",
                       f"حرف الجر «{esc(p)}»{mean} يحدد حالة الاسم الذي بعده."
                       + (" وهذا الحرف يأخذ أكثر من حالة، والمعنى هو الذي يحدد الحالة المناسبة." if multi else
                          f" وهو يتطلب دائماً {esc(RU[code])}.")))
        why = f"جاءت «{word}» في صيغة {esc(cname)} لأنها بعد «{esc(key)}»."
        if p in ("в", "на"):
            why += (" السؤال «куда؟» (إلى أين؟) يعني винительный، أما «где؟» (أين؟) فيعني предложный. "
                    f"هنا الحالة {esc(RU[code])}.")
        elif multi:
            why += " المعنى في هذه الجملة هو الذي رجّح هذه الحالة."
        blocks.append(("🔍", "تطبيقها في هذه الجملة", why))
        if info:
            blocks.append(("✍️", "مثال", f"{esc(info[1])} — {esc(info[2])}"))
        blocks.append(("⚠️", "انتبه", "احفظ حرف الجر مع حالته كوحدة واحدة (у + родительный، к + дательный) بدل حفظ الحالات منفصلة."))

    elif kind == "rektion":
        info = VERB_INFO.get(key)
        blocks.append(("📌", "القاعدة",
                       f"بعض الأفعال تتطلب حالة معينة لمتممها مباشرة بلا حرف جر. الفعل «{esc(key)}» يتطلب {esc(RU[code])}."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة",
                       f"«{word}» هو متمم الفعل «{head}»، فأخذ صيغة {esc(cname)}."))
        if info:
            blocks.append(("✍️", f"مثال: {esc(key)} = {esc(info[0])}", f"{esc(info[1])} — {esc(info[2])}"))
            blocks.append(("⚠️", "قارن مع العربية", esc(info[3])))
        else:
            blocks.append(("⚠️", "انتبه", "احفظ هذا الفعل مع حالته كوحدة واحدة (فعل + حالة)."))

    elif kind == "comparative":
        blocks.append(("📌", "القاعدة", "بعد صيغة التفضيل (старше، меньше، больше...) إذا لم تأتِ «чем»، يأتي المقارَن به في родительный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» هو المقارَن به بعد «{head}»، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "Брат старше меня. — أخي أكبر مني. وبـ«чем»: Брат старше, чем я. (я في именительный)"))
        blocks.append(("⚠️", "قارن مع العربية", "«أكبر مني» تقابل «старше меня»: الضمير بعد «من» يقابله родительный."))

    elif kind == "negation":
        blocks.append(("📌", "القاعدة", "بعد «нет» (وفي الماضي «не было») يأتي الشيء المنفي في родительный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» هو الشيء المنفي بعد «{head}»، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "У меня нет времени. — ليس عندي وقت. / В комнате не было стола. — لم تكن في الغرفة طاولة."))
        blocks.append(("⚠️", "انتبه", "المثبَت يأتي في именительный (У меня есть время)، والمنفي يتحول إلى родительный (У меня нет времени)."))

    elif kind == "obj":
        blocks.append(("📌", "القاعدة", "المفعول به المباشر (الذي يقع عليه الفعل) يأتي في винительный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» هو الذي يقع عليه الفعل «{head}»، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "Я читаю книгу. — أقرأ كتاباً. / Я вижу брата. — أرى أخي."))
        blocks.append(("⚠️", "انتبه", "في المذكر الحي والجمع الحي يتطابق винительный في الشكل مع родительный، وفي غير الحي مع именительный."))

    elif kind == "iobj":
        blocks.append(("📌", "القاعدة", "المفعول غير المباشر (المتلقي: لمن؟) يأتي في дательный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» هو المتلقي لفعل «{head}»، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "Я дал брату книгу. — أعطيت أخي كتاباً (брату: المتلقي، книгу: المفعول المباشر)."))
        blocks.append(("⚠️", "قارن مع العربية", "في العربية «أخي» و«كتاباً» كلاهما منصوب، أما الروسية فتفرّق بينهما: дательный للمتلقي وвинительный للمفعول المباشر."))

    elif kind == "nsubj":
        blocks.append(("📌", "القاعدة", "الفاعل (من يقوم بالفعل) أو المبتدأ يأتي في именительный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» هو الفاعل، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "Студент читает книгу. — الطالب يقرأ كتاباً."))
        blocks.append(("⚠️", "انتبه", "ترتيب الكلمات حر في الروسية: الحالة هي التي تدلّ على الدور لا الموقع (Книгу читает студент)."))

    elif kind == "instrumental":
        blocks.append(("📌", "القاعدة", "الأداة أو الوسيلة التي يتم بها الفعل تأتي في творительный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» هو الوسيلة أو الأداة المرتبطة بـ «{head}»، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "Я пишу ручкой. — أكتب بالقلم."))
        blocks.append(("⚠️", "قارن مع العربية", "العربية تستعمل حرف الجر «بـ»، والروسية تستعمل الحالة وحدها بلا حرف جر."))

    elif kind == "genitive_attr":
        blocks.append(("📌", "القاعدة", "الاسم الذي يحدد اسماً آخر (الإضافة والانتماء) يأتي في родительный."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» يحدد الاسم «{head}»، فجاء في {esc(cname)}."))
        blocks.append(("✍️", "مثال", "книга брата — كتاب الأخ. / дом моего отца — بيت أبي."))
        blocks.append(("⚠️", "قارن مع العربية", "تقابل الإضافة (المضاف إليه)، لكن ترتيب الروسية: المُضاف ثم المضاف إليه بحالة родительный."))

    elif kind == "agreement":
        blocks.append(("📌", "القاعدة", "الصفة وضمائر الإشارة والملكية (большой، этот، мой) تتبع الاسم الذي تصفه في الحالة والجنس والعدد."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» تصف «{head}»، لذلك أخذت حالته وهي {esc(cname)}."))
        blocks.append(("✍️", "مثال", "в большом доме — في بيت كبير (كلتا الكلمتين: предложный، مذكر، مفرد)."))
        blocks.append(("⚠️", "انتبه", "ابحث عن الاسم أولاً وحدد حالته، ثم اجعل الصفة مثله."))

    elif kind == "possessive_fixed":
        blocks.append(("📌", "القاعدة", "الضمائر الملكية его (ـه) وее (ـها) وих (ـهم) ثابتة: لا تتغير بحسب الحالة أو الجنس أو العدد."))
        blocks.append(("🔍", "تطبيقها في هذه الجملة", f"«{word}» تصف الاسم «{head}» وتبقى كما هي مهما كانت حالة الاسم."))
        blocks.append(("✍️", "مثال", "с его другом — مع صديقه. / с её другом — مع صديقها. / с их другом — مع صديقهم."))
        blocks.append(("⚠️", "انتبه", "لا تخلطها بالضمير الشخصي: «Я вижу его» (أراه: винительный) و«у него» (عنده: родительный، ويُضاف н- بعد حرف الجر)."))

    # بلوك عام عن الحالة نفسها
    if code in CASE_INFO:
        ci = CASE_INFO[code]
        uses = "".join(f"<li>{esc(u[0])}: <b>{esc(u[1])}</b> — {esc(u[2])}</li>" for u in ci["uses"][:4])
        blocks.append(("📖", f"عن حالة {RU[code]}",
                       f"{esc(ci['summary'])}<br><b>الأسئلة:</b> {esc(ci['q'])}<ul>{uses}</ul>"
                       f"<b>مقارنة تقريبية مع العربية:</b> {esc(ci['arabic'])}"))
    nk = r.get("note_kind", "none")
    if nk in NOTE_INFO:
        title, text = NOTE_INFO[nk]
        blocks.append(("🧩", f"لماذا تتشابه الأشكال؟ {title}", esc(text)))
    return blocks
